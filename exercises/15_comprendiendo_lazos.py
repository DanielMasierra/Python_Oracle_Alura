clientes = ["Juan", "Maria", "Carlos", "Ana", "Beatriz"]

for cliente in clientes: 
    print(cliente)


#El lazo for es más adecuado en este caso, ya que sabemos el número
# exacto de elementos en la lista (5 nombres). 
# Con el lazo for, recorreremos todos los elementos de manera clara y directa, 
# sin necesidad de gestionar manualmente un contador o condición de parada.

